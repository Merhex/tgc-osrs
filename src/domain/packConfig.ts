import type { Rarity } from '../data/cards';

/** A slot draws one card from the listed rarities using the given weights. */
export interface SlotRule {
  /** Relative weights per rarity. Rarities absent or with weight 0 are not eligible. */
  weights: Partial<Record<Rarity, number>>;
}

export interface PackConfig {
  id: 'prototype-booster' | 'showcase' | string;
  label: string;
  slots: SlotRule[];
  /** When false, no card definition may appear twice in one pack. */
  allowDuplicatesWithinPack: boolean;
  /** Development packs are labelled in the UI. */
  development?: boolean;
}

const nonLegendary: SlotRule = { weights: { Rare: 35, Epic: 65 } };
const legendary: SlotRule = { weights: { Legendary: 1 } };

/**
 * Default "Prototype Booster": slots 1–9 are Rare/Epic (35/65), slot 10 is a
 * Legendary chosen uniformly. These odds are prototype settings, not OSRS drop rates.
 */
export const PROTOTYPE_BOOSTER: PackConfig = {
  id: 'prototype-booster',
  label: 'Prototype Booster',
  slots: [...Array.from({ length: 9 }, () => nonLegendary), legendary],
  allowDuplicatesWithinPack: true,
};

/** Showcase mode is generated by a dedicated function; this config describes its shape. */
export const SHOWCASE_PACK: PackConfig = {
  id: 'showcase',
  label: 'Development Showcase Pack',
  slots: [...Array.from({ length: 6 }, () => ({ weights: { Rare: 1, Epic: 1 } })), ...Array.from({ length: 4 }, () => legendary)],
  allowDuplicatesWithinPack: false,
  development: true,
};

export type PackMode = 'prototype-booster' | 'showcase';

export const PACK_SIZE = 10;
